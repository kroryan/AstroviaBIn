#!/usr/bin/env node
// Inventory and full license texts of every production JavaScript dependency (direct and transitive)
// that AstroviaBin ships: the server's node_modules and the code compiled into the web client.
// usage: node tools/scripts/js-licenses.mjs <inventory.md> <license-texts.txt>
import { execFileSync } from 'node:child_process';
import { existsSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const repo = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..');
const [inventoryPath, textsPath] = process.argv.slice(2);
if (!inventoryPath || !textsPath) {
  console.error('usage: node tools/scripts/js-licenses.mjs <inventory.md> <license-texts.txt>');
  process.exit(2);
}

const tree = JSON.parse(execFileSync('npm', ['ls', '--omit=dev', '--all', '--json', '--long'], { cwd: repo, maxBuffer: 64 * 1024 * 1024, shell: process.platform === 'win32' }).toString()); // npm is a .cmd on Windows
const packages = new Map();
const walk = node => {
  for (const [name, child] of Object.entries(node.dependencies || {})) {
    if (!child.version || !child.path) continue;
    const key = `${name}@${child.version}`;
    if (!packages.has(key)) {
      packages.set(key, { name, version: child.version, dir: child.path });
      walk(child);
    }
  }
};
walk(tree);

const licenseFile = dir => {
  if (!existsSync(dir)) return null;
  const file = readdirSync(dir).find(entry => /^(licen[cs]e|copying|notice)(\.|-|$)/i.test(entry));
  return file ? path.join(dir, file) : null;
};

const rows = [];
const texts = [];
for (const item of [...packages.values()].sort((a, b) => a.name.localeCompare(b.name))) {
  let manifest = {};
  try { manifest = JSON.parse(readFileSync(path.join(item.dir, 'package.json'), 'utf8')); } catch { /* keep defaults */ }
  if (manifest.private && !manifest.license) continue; // workspace packages of this repository
  const license = typeof manifest.license === 'string' ? manifest.license
    : Array.isArray(manifest.licenses) ? manifest.licenses.map(entry => entry.type || entry).join(' OR ') : 'see license file';
  const file = licenseFile(item.dir);
  rows.push(`| ${item.name} | ${item.version} | ${license} | ${file ? 'included below' : 'no license file in the package'} |`);
  if (file) texts.push(`${'='.repeat(78)}\n${item.name} ${item.version} (${license})\n${'='.repeat(78)}\n${readFileSync(file, 'utf8').trim()}\n`);
}

writeFileSync(inventoryPath, [
  '# JavaScript packages',
  '',
  'Production dependencies of the AstroviaBin server and web client (direct and transitive), generated by',
  '`tools/scripts/js-licenses.mjs` from `npm ls --omit=dev`. The web client compiles parts of these packages into',
  'its JavaScript bundle; their full license texts ship with the installers in `licenses/javascript-licenses.txt`.',
  '',
  '| Package | Version | License | License text |',
  '|---|---|---|---|',
  ...rows,
  '',
].join('\n'));
writeFileSync(textsPath, `Third-party JavaScript licenses shipped with AstroviaBin\n\n${texts.join('\n')}`);
console.log(`${rows.length} JavaScript packages, ${texts.length} license texts`);
